// Downloads the default-enabled desktop filter lists from Brave's catalog.
// Live tests (`cargo test`) and the redirect bench read the result from
// data/live-filters.txt. Tests skip locally if the file is missing and fail
// on CI (CI=true).
//
// Usage: node data/fetch-live-lists.js

const assert = require("node:assert");
const fs = require("node:fs");
const https = require("node:https");
const path = require("node:path");

const CATALOG_URL =
  "https://raw.githubusercontent.com/brave/adblock-resources/master/filter_lists/list_catalog.json";
const DESKTOP_PLATFORMS = new Set(["LINUX", "WINDOWS", "MAC"]);
const OUT_FILE = path.join(__dirname, "live-filters.txt");

function isDesktopList(entry) {
  if (!entry.default_enabled) {
    return false;
  }
  const platforms = entry.platforms || [];
  return (
    platforms.length === 0 ||
    platforms.some((platform) => DESKTOP_PLATFORMS.has(platform))
  );
}

function downloadText(url) {
  console.log(`Downloading ${url}`);
  assert.ok(url.startsWith("https://"), `Expected https URL, got '${url}'`);
  return new Promise((resolve, reject) => {
    https
      .get(url, (res) => {
        if (res.statusCode !== 200) {
          res.resume();
          reject(new Error(`Failed download of '${url}'`));
          return;
        }
        let body = "";
        res.on("data", (chunk) => {
          body += chunk;
        });
        res.on("end", () => resolve(body));
        res.on("error", reject);
      })
      .on("error", reject);
  });
}

async function main() {
  const catalog = JSON.parse(await downloadText(CATALOG_URL));
  const sources = catalog
    .filter(isDesktopList)
    .flatMap((entry) => entry.sources);

  if (sources.length <= 10) {
    throw new Error(`Expected 10+ filter lists, got ${sources.length}`);
  }

  const lists = [];
  for (const source of sources) {
    const text = await downloadText(source.url);
    lists.push(`! Source: ${source.url}\n${text}`);
  }

  const header = [
    "! Auto-generated by data/fetch-live-lists.js. Do not edit.",
    "! Regenerated on CI before tests; run locally with: node data/fetch-live-lists.js",
    "",
  ].join("\n");

  fs.writeFileSync(OUT_FILE, header + lists.join("\n"));
  console.log(`Wrote ${OUT_FILE} (${sources.length} lists)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
